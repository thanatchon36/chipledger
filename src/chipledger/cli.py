"""Command-line interface: `chipledger validate | derive | coverage | analyze | figures | paper`."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
import typer
import yaml

from chipledger import __version__, identity, schema

app = typer.Typer(no_args_is_help=True, help="An accounting identity for AI-accelerator performance growth.")
PRODUCTS = Path("data/accelerators.csv")
SOURCES = Path("data/sources.csv")
RESULTS = Path("results")


@app.command()
def version() -> None:
    """Print the version."""
    typer.echo(__version__)


@app.command()
def validate(products: Path = PRODUCTS, sources: Path = SOURCES) -> None:
    """Check the dataset: columns, types, dates, provenance, consistency. Any error exits 1."""
    raw = schema.read_raw(products)
    rep = schema.validate(raw, schema.read_raw(sources))
    for w in rep.warnings:
        typer.echo(f"warning: {w}")
    for e in rep.errors:
        typer.echo(f"error: {e}", err=True)
    typer.echo(f"{len(raw)} products, {len(rep.errors)} errors, {len(rep.warnings)} warnings")
    if not rep.ok:
        raise typer.Exit(1)


@app.command()
def derive(products: Path = PRODUCTS, out: Path = RESULTS / "derived.csv") -> None:
    """Compute the derived columns of PREREGISTRATION §2, check the identities, write results/derived.csv."""
    d = identity.derive(schema.load(products))
    worst = identity.check(d)
    out.parent.mkdir(parents=True, exist_ok=True)
    d.to_csv(out, index=False)
    complete = int(d["sample_a"].sum())
    typer.echo(
        f"{len(d)} products, {complete} in the decomposition sample ({int(d['sample_an'].sum())} in A′), "
        f"max |residual| {worst:.1e}; wrote {out}"
    )


@app.command()
def coverage(products: Path = PRODUCTS, out: Path = Path("data/coverage.md")) -> None:
    """Write data/coverage.md: which products lack which decomposition fields (reason: the notes column)."""
    df = schema.load(products)
    lines = [
        "# Coverage",
        "",
        "Products outside the decomposition sample (PREREGISTRATION.md §3) and the fields they lack.",
        "Generated by `chipledger coverage`; the reason is the product's `notes` entry in the dataset.",
        "",
        "| product | missing | notes |",
        "|---|---|---|",
    ]
    n = 0
    for _, row in df.iterrows():
        gaps = [c for c in schema.DECOMPOSITION if pd.isna(row[c])]
        if not any(pd.notna(row[c]) for c in schema.DENSE):
            gaps.append("a dense rate")
        if gaps:
            n += 1
            lines.append(f"| {row['product']} | {', '.join(gaps)} | {row['notes']} |")
    if n == 0:
        lines.append("| (none) | | |")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    typer.echo(f"{n} of {len(df)} products outside the decomposition sample; wrote {out}")


def _not_yet(phase: str) -> None:
    typer.echo(f"not built yet: planned for {phase} (see STATUS.md)")


@app.command()
def analyze(
    products: Path = PRODUCTS,
    sources: Path = SOURCES,
    nodes: Path = Path("data/nodes.csv"),
    seed: Path = Path("configs/seed.yaml"),
    mlperf: Path = Path("data/mlperf.csv"),
    out: Path = RESULTS,
) -> None:
    """Estimators (a)–(c), H1–H7, sensitivities and secondary analyses: results/numbers.json and tables."""
    from chipledger.analysis import run, tables

    ml = pd.read_csv(mlperf) if mlperf.exists() else None
    numbers = run.run(
        schema.read_raw(products),
        schema.read_raw(sources),
        pd.read_csv(nodes),
        yaml.safe_load(seed.read_text()),
        ml,
    )
    (out / "tables").mkdir(parents=True, exist_ok=True)
    (out / "numbers.json").write_text(
        json.dumps(numbers, indent=1, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    for name, md in tables.all_tables(numbers).items():
        (out / "tables" / name).write_text(md, encoding="utf-8")
    for k, v in numbers["hypotheses"].items():
        typer.echo(f"{k}: {v['verdict']}")
    typer.echo(f"wrote {out / 'numbers.json'} and {out / 'tables'}/")


@app.command()
def figures() -> None:
    """Figures F1–F7 as SVG and PNG. Phase 4."""
    _not_yet("Phase 4")


@app.command()
def paper() -> None:
    """Fill paper/paper.md from results/numbers.json and build the PDF and the web page. Phase 4."""
    _not_yet("Phase 4")
